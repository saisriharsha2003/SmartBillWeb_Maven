CREATE TABLE BILL (
    BILL_NUMBER INTEGER NOT NULL PRIMARY KEY,
    DUE_AMOUNT DOUBLE,
    BILL_AMOUNT DOUBLE,
    DUE_DATE VARCHAR(20),
    PENALTY DOUBLE,
    STATUS VARCHAR(20),
    METER_NUMBER VARCHAR(20)
);

CREATE TABLE PAYMENT (
    TRANSACTION_NUMBER INTEGER NOT NULL PRIMARY KEY,
    BILL_NUMBER INTEGER,
    PAID_AMOUNT DOUBLE,
    TRANSACTION_MODE VARCHAR(50),
    TRANSACTION_DATE VARCHAR(50),
    CONSUMER_ID BIGINT,
    METER_NUMBER VARCHAR(20)
);

CREATE TABLE COMPLAINT (
    COMPLAINT_ID INTEGER NOT NULL PRIMARY KEY,
    LANDMARK VARCHAR(50),
    SERVICE VARCHAR(50),
    CATEGORY VARCHAR(50),
    MOBILE BIGINT,
    CONTACT VARCHAR(50),
    PROBLEM VARCHAR(200),
    ADDRESS VARCHAR(200),
    COMPLAINT_STATUS VARCHAR(200),
    CONSUMER_ID BIGINT
);

