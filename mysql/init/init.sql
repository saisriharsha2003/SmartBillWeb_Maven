CREATE TABLE CONSUMER (
    CONSUMER_ID BIGINT NOT NULL PRIMARY KEY,
    METER_NUMBER VARCHAR(20) UNIQUE,
    TITLE VARCHAR(20),
    CONSUMER_NAME VARCHAR(100),
    EMAIL VARCHAR(50),
    MOBILE BIGINT,
    GENDER VARCHAR(20),
    USER_NAME VARCHAR(50),
    PASSWORD VARCHAR(50)
);

CREATE TABLE LOGIN (
    USERNAME VARCHAR(50) PRIMARY KEY,
    PASSWORD VARCHAR(50),
    CONSUMER_ID BIGINT,
    STATUS VARCHAR(20)
);

CREATE TABLE ADMIN_LOGIN (
